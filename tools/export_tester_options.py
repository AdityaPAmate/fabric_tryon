"""Export only public option keys/validation metadata for the local tester."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fabricapp.ai.pose_registry import get_pose_options, get_pose_metadata
from fabricapp.ai.detail_engine import _rules_for
from fabricapp.ai.router import IMPLEMENTED_GARMENT_TYPES


def main():
    config = {}
    for garment in sorted(IMPLEMENTED_GARMENT_TYPES):
        config[garment] = {
            'poses': {pose: {key: bool(get_pose_metadata(garment, pose).get(key))
                             for key in ('hides_face', 'requires_full_body')}
                      for pose in get_pose_options(garment)},
            'details': [{'slot': rule['slot'], 'styles': rule.get('styles'), 'options': list(rule['options'])}
                        for rule in _rules_for(garment)],
        }
    (ROOT / 'tools/tester_ui/js/api_options.js').write_text(
        '/* Generated by tools/export_tester_options.py. */\nglobalThis.TRYON_API_OPTIONS = '
        + json.dumps(config, indent=2) + ';\n', encoding='utf-8')
    print(f'Exported public options for {len(config)} garments.')


if __name__ == '__main__':
    main()
